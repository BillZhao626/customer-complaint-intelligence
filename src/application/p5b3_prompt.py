def messages(email, runtime=None):
    user=inherited(email,'B')[1]
    from src.application.urgency_context_v2 import signals
    data=json.loads(user[1])
    hints=[dict(quote=e['quote'],signals=signals(e['quote'])) for e in data['evidence_catalog']]
    return [('system',system()),('human',json.dumps(dict(untrusted_email=data,trusted_runtime=runtime or {},evidence_signals=hints),ensure_ascii=False))]
